#!/usr/bin/env python3
"""Create a KLEE driver that maps symbolic int32 values to numeric argv inputs."""
from __future__ import annotations
import argparse
import json
from pathlib import Path


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("source", type=Path)
    ap.add_argument("output", type=Path)
    ap.add_argument("--arg-count", type=int, required=True)
    args = ap.parse_args()
    source = args.source.resolve()
    count = args.arg_count
    if not source.is_file() or source.suffix.lower() != ".c":
        ap.error("source must be an existing .c file")
    if count < 1:
        ap.error("arg-count must be at least 1")

    include_path = json.dumps(str(source))
    c = f'''/* Generated by KLEE Path Test Generator. Do not edit. */
#include <stdint.h>
#include <stddef.h>
#include <stdlib.h>

extern void klee_make_symbolic(void *address, size_t nbytes, const char *name);

#define KLEE_PG_ARG_COUNT {count}
_Static_assert(sizeof(int) == sizeof(int32_t), "This input adapter requires 32-bit int.");
static int32_t klee_pg_values[KLEE_PG_ARG_COUNT];
/* Unique argv pointers: atoi is intercepted and mapped to the symbolic int32. */
static char klee_pg_tokens[KLEE_PG_ARG_COUNT][2];
static char *klee_pg_argv[KLEE_PG_ARG_COUNT + 2];

static int klee_pg_atoi(const char *text) {{
    for (int i = 0; i < KLEE_PG_ARG_COUNT; ++i) {{
        if (text == klee_pg_tokens[i])
            return (int)klee_pg_values[i];
    }}
    /* Preserve ordinary parsing for non-argv strings used inside the source. */
    return (int)strtol(text, NULL, 10);
}}

#define main klee_pg_target_main
#define atoi klee_pg_atoi
#include {include_path}
#undef atoi
#undef main

int main(int runtime_argc, char **runtime_argv) {{
    (void)runtime_argc;
    (void)runtime_argv;

    klee_make_symbolic(klee_pg_values, sizeof(klee_pg_values), "argv_values");

    klee_pg_argv[0] = (char *)"klee-generated";
    for (int i = 0; i < KLEE_PG_ARG_COUNT; ++i) {{
        klee_pg_tokens[i][0] = '0';
        klee_pg_tokens[i][1] = '\\0';
        klee_pg_argv[i + 1] = klee_pg_tokens[i];
    }}
    klee_pg_argv[KLEE_PG_ARG_COUNT + 1] = NULL;

    return klee_pg_target_main(KLEE_PG_ARG_COUNT + 1, klee_pg_argv);
}}
'''
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(c, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
